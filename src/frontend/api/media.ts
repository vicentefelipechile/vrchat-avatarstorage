import { ApiClient } from './client';

// =========================================================================================================
// Domain
// =========================================================================================================

export class MediaApi {
	constructor(private readonly client: ApiClient) {}
	Status(uuid: string) {
		return this.client.get<{ processed: boolean }>(`/api/media/${encodeURIComponent(uuid)}/status`);
	}
}
