// =========================================================================================================
// HTTP polling updates — no WebSocket transport.
// =========================================================================================================

// =========================================================================================================
// Imports
// =========================================================================================================

import { ApiClient } from './client';
import { query } from './types';

// =========================================================================================================
// Types
// =========================================================================================================

export interface UpdatesResult {
	now: number;
	changes: { scope: 'avatars' | 'assets' | 'clothes' | 'blog' | 'comments'; updated_at: number }[];
}

// =========================================================================================================
// Domain
// =========================================================================================================

export class UpdatesApi {
	constructor(private readonly client: ApiClient) {}
	Since(since?: number) {
		return this.client.get<UpdatesResult>(`/api/updates${query({ since })}`);
	}
}
